const KEY = "emberline_lang";

// Storage throws (not returns null) in Safari with "Block all cookies" and in any
// browser with site data blocked for the origin. readLocale() runs inside the
// I18nProvider's useState initializer, so an unguarded access unwound React to the
// ErrorBoundary and every page rendered "Desk failed to render." instead of the site.
function readStored(): string | null {
  try {
    return localStorage.getItem(KEY);
  } catch {
    return null;
  }
}

export function readLocale(): Locale {
  const params = new URLSearchParams(location.search).get("lang");
  if (params === "es" || params === "fr" || params === "en") return params;
  const stored = readStored();
  if (stored === "es" || stored === "fr" || stored === "en") return stored;
  const accept = (navigator.language || "en").toLowerCase();
  if (accept.startsWith("es")) return "es";
  if (accept.startsWith("fr")) return "fr";
  return "en";
}

export function writeLocale(locale: Locale) {
  try {
    localStorage.setItem(KEY, locale);
  } catch {
    /* storage blocked — the ?lang= param below still carries the choice */
  }
  const url = new URL(location.href);
  url.searchParams.set("lang", locale);
  history.replaceState(null, "", url.toString());
  document.documentElement.lang = locale;
}

